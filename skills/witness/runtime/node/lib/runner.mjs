// Runs specs under the Witness shim without touching user files.
//
// 1. Mirror the relevant test directories into .witness/tmp/<run>/
// 2. Rewrite '@playwright/test' imports in the mirror to the shim; re-point relative imports
//    that leave the mirrored tree to their original absolute location.
// 3. Generate a temporary config (wrapping the project's config, or a minimal one for raw replays).
// 4. Run `npx playwright test` from the project directory and collect evidence JSON.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { exists, copyDir, walk, run, stamp, readJSON, log } from './util.mjs';
import { projectPaths } from './config.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SHIM = path.join(HERE, '..', 'shim', 'witness-shim.ts');
const CODE_EXT = /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs)$/;

function npx() { return process.platform === 'win32' ? 'npx.cmd' : 'npx'; }

/** Ask Playwright which test directories the project config uses. */
export async function projectTestDirs(projectDir, cfg) {
  const configFile = path.resolve(projectDir, cfg.playwrightConfig);
  const r = await run(npx(), ['playwright', 'test', '--list', '--reporter=json', '-c', configFile], { cwd: projectDir, timeoutMs: 120000 });
  const start = r.out.indexOf('{');
  if (start < 0) throw new Error('Could not list tests with the project config:\n' + r.out.slice(0, 2000));
  let report;
  try { report = JSON.parse(r.out.slice(start, r.out.lastIndexOf('}') + 1)); } catch (e) {
    throw new Error('Could not parse Playwright --list output: ' + e.message);
  }
  const dirs = new Set((report.config?.projects || []).map((p) => p.testDir).filter(Boolean));
  if (!dirs.size) dirs.add(path.resolve(projectDir, cfg.testDir));
  // Drop nested duplicates (keep outermost).
  const sorted = [...dirs].sort((a, b) => a.length - b.length);
  return sorted.filter((d, i) => !sorted.slice(0, i).some((o) => d === o || d.startsWith(o + path.sep)));
}

function rewriteImports(code, { origFile, origRoot, mirrorFile, shimNoExt }) {
  const replaceSpec = (spec) => {
    if (spec === '@playwright/test') {
      let r = path.relative(path.dirname(mirrorFile), shimNoExt).split(path.sep).join('/');
      if (!r.startsWith('.')) r = './' + r;
      return r;
    }
    if (spec.startsWith('.')) {
      const target = path.resolve(path.dirname(origFile), spec);
      if (target === origRoot || target.startsWith(origRoot + path.sep)) return spec;
      return target.split(path.sep).join('/');
    }
    return spec;
  };
  return code
    .replace(/(\bfrom\s*)(['"])([^'"\n]+)\2/g, (m, a, q, s) => `${a}${q}${replaceSpec(s)}${q}`)
    .replace(/(\bimport\s*)(['"])([^'"\n]+)\2/g, (m, a, q, s) => `${a}${q}${replaceSpec(s)}${q}`)
    .replace(/(\b(?:require|import)\s*\(\s*)(['"])([^'"\n]+)\2/g, (m, a, q, s) => `${a}${q}${replaceSpec(s)}${q}`);
}

function mirror(roots, runDir) {
  const shimDir = path.join(runDir, '__witness__');
  fs.mkdirSync(shimDir, { recursive: true });
  fs.copyFileSync(SHIM, path.join(shimDir, 'witness-shim.ts'));
  const shimNoExt = path.join(shimDir, 'witness-shim');
  const map = [];
  roots.forEach((root, i) => {
    const dest = path.join(runDir, `m${i}`);
    copyDir(root, dest, { exclude: ['node_modules', '.witness', '.git', 'test-results', 'playwright-report'] });
    for (const f of walk(dest, (p) => CODE_EXT.test(p))) {
      const origFile = path.join(root, path.relative(dest, f));
      const code = fs.readFileSync(f, 'utf8');
      const next = rewriteImports(code, { origFile, origRoot: root, mirrorFile: f, shimNoExt });
      if (next !== code) fs.writeFileSync(f, next);
    }
    map.push([root, dest]);
  });
  return map;
}

function mapPath(map, p) {
  for (const [from, to] of map) if (p === from || p.startsWith(from + path.sep)) return to + p.slice(from.length);
  return null;
}

function projectConfigSource({ configFile, map, runDir }) {
  const noExt = configFile.replace(/\.(ts|js|mjs|cjs|mts|cts)$/, '').split(path.sep).join('/');
  return `// Generated by Witness. Wraps the project's Playwright config to run mirrored, instrumented tests.
import * as baseModule from ${JSON.stringify(noExt)};
import * as path from 'path';
const CONFIG_DIR = ${JSON.stringify(path.dirname(configFile))};
const MAP: [string, string][] = ${JSON.stringify(map)};
function mapDir(d?: string) {
  const abs = path.resolve(CONFIG_DIR, d || '.');
  for (const [from, to] of MAP) if (abs === from || abs.startsWith(from + path.sep)) return to + abs.slice(from.length);
  return abs;
}
const absIf = (p: any) => (typeof p === 'string' && !path.isAbsolute(p) ? path.resolve(CONFIG_DIR, p) : p);
const b: any = (baseModule as any).default?.default ?? (baseModule as any).default ?? baseModule;
const webServer = b.webServer === undefined ? undefined
  : (Array.isArray(b.webServer) ? b.webServer : [b.webServer]).map((w: any) => ({ ...w, cwd: w.cwd ? path.resolve(CONFIG_DIR, w.cwd) : CONFIG_DIR }));
const config: any = {
  ...b,
  testDir: mapDir(b.testDir),
  outputDir: ${JSON.stringify(path.join(runDir, 'out'))},
  reporter: [['line']],
  retries: 0,
  workers: 1,
  fullyParallel: false,
  forbidOnly: false,
};
if (b.globalSetup) config.globalSetup = Array.isArray(b.globalSetup) ? b.globalSetup.map(absIf) : absIf(b.globalSetup);
if (b.globalTeardown) config.globalTeardown = Array.isArray(b.globalTeardown) ? b.globalTeardown.map(absIf) : absIf(b.globalTeardown);
if (webServer) config.webServer = webServer;
if (b.projects) config.projects = b.projects.map((p: any) => ({ ...p, testDir: mapDir(p.testDir ?? b.testDir) }));
export default config;
`;
}

// Raw replays use the project's browser settings (channel, locale, test id attribute, ...) from its
// config and the verify project, but none of its projects/dependencies; login comes from the role's
// saved storage state.
function rawConfigSource({ testDir, runDir, cfg, storageState, projectConfigFile }) {
  const overrides = {
    headless: true,
    locale: cfg.browser.locale,
    timezoneId: cfg.browser.timezoneId,
    viewport: cfg.browser.viewport ? { width: cfg.browser.viewport[0], height: cfg.browser.viewport[1] } : undefined,
    testIdAttribute: cfg.testIdAttribute,
    actionTimeout: 15000,
    navigationTimeout: 30000,
    storageState: storageState || undefined,
  };
  const channel = process.env.WITNESS_BROWSER_CHANNEL || cfg.browser.channel;
  if (channel) overrides.channel = channel;
  const importLine = projectConfigFile && exists(projectConfigFile)
    ? `import * as baseModule from ${JSON.stringify(projectConfigFile.replace(/\.(ts|js|mjs|cjs|mts|cts)$/, '').split(path.sep).join('/'))};\nconst b: any = (baseModule as any).default?.default ?? (baseModule as any).default ?? baseModule;`
    : 'const b: any = {};';
  return `// Generated by Witness for replaying a raw recording.
${importLine}
const verifyProject = ${JSON.stringify(cfg.verifyProject || null)};
const p: any = (b.projects || []).find((x: any) => x.name === verifyProject) || (b.projects || []).find((x: any) => !/setup/i.test(x.name || '')) || {};
const overrides: any = ${JSON.stringify(overrides, null, 2)};
for (const k of Object.keys(overrides)) if (overrides[k] === undefined) delete overrides[k];
const use: any = { ...(b.use || {}), ...(p.use || {}), ...overrides };
if (!overrides.storageState) delete use.storageState;
export default {
  testDir: ${JSON.stringify(testDir)},
  outputDir: ${JSON.stringify(path.join(runDir, 'out'))},
  reporter: [['line']],
  retries: 0,
  workers: 1,
  timeout: 120000,
  use,
};
`;
}

/**
 * Run one spec file under the shim.
 * opts: { projectDir, cfg, spec, mode, useProjectConfig, repeat, throttle, vacuityPlan, storageState, label, echo }
 */
export async function runSpec(opts) {
  const { projectDir, cfg, mode } = opts;
  const P = projectPaths(projectDir);
  const spec = path.resolve(projectDir, opts.spec);
  if (!exists(spec)) throw new Error(`Spec not found: ${spec}`);
  const runDir = path.join(P.tmp, `${opts.label || mode}-${stamp()}`);
  fs.mkdirSync(runDir, { recursive: true });

  let roots = opts.useProjectConfig ? await projectTestDirs(projectDir, cfg) : [path.dirname(spec)];
  if (!roots.some((r) => spec.startsWith(r + path.sep))) roots = [...roots, path.dirname(spec)];
  const map = mirror(roots, runDir);
  const mirroredSpec = mapPath(map, spec);

  const configPath = path.join(runDir, 'witness.config.ts');
  if (opts.useProjectConfig) {
    fs.writeFileSync(configPath, projectConfigSource({ configFile: path.resolve(projectDir, cfg.playwrightConfig), map, runDir }));
  } else {
    fs.writeFileSync(configPath, rawConfigSource({ testDir: map[0][1], runDir, cfg, storageState: opts.storageState, projectConfigFile: path.resolve(projectDir, cfg.playwrightConfig) }));
  }

  const evidenceDir = path.join(runDir, 'evidence');
  const env = {
    ...process.env,
    WITNESS_MODE: mode,
    WITNESS_EVIDENCE_DIR: evidenceDir,
    WITNESS_TEST_ID_ATTRIBUTE: cfg.testIdAttribute || 'data-testid',
    WITNESS_CPU_THROTTLE: String(opts.throttle || 0),
  };
  if (opts.vacuityPlan) {
    const planFile = path.join(runDir, 'vacuity-plan.json');
    fs.writeFileSync(planFile, JSON.stringify(opts.vacuityPlan));
    env.WITNESS_VACUITY_PLAN = planFile;
  }
  const args = ['playwright', 'test', '-c', configPath, mirroredSpec];
  if (opts.useProjectConfig && cfg.verifyProject) args.push('--project', cfg.verifyProject);
  if (opts.repeat && opts.repeat > 1) args.push('--repeat-each', String(opts.repeat));
  log(`running ${mode}${opts.repeat > 1 ? ` x${opts.repeat}` : ''}${opts.throttle > 1 ? ` (cpu x${opts.throttle})` : ''}: ${path.relative(projectDir, spec)}`);
  const r = await run(npx(), args, { cwd: projectDir, env, timeoutMs: opts.timeoutMs || 15 * 60000, echo: opts.echo });
  fs.writeFileSync(path.join(runDir, 'output.log'), r.out);

  const evidence = walk(evidenceDir, (p) => p.endsWith('.json'))
    .map((f) => readJSON(f))
    .filter((e) => path.resolve(e.file) === mirroredSpec)
    .map((e) => ({ ...e, file: path.relative(projectDir, spec).split(path.sep).join('/') }))
    .sort((a, b) => a.repeat - b.repeat || String(a.title).localeCompare(String(b.title)));
  return { code: r.code, output: r.out, runDir, evidence };
}
